  if (pet.templateId && PET_EXCLUSIVE_APPEARANCES[pet.templateId]) {
    return {
      ...PET_EXCLUSIVE_APPEARANCES[pet.templateId],
      customArtworkUrl: DISTINCT_PET_ARTWORKS[pet.templateId] || PET_EXCLUSIVE_APPEARANCES[pet.templateId].customArtworkUrl,
    };
  }

